const LangContext = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const savedLang = localStorage.getItem('lang')
    return Object.hasOwn(translations, savedLang) ? savedLang : 'ru'
  })

  const t = useCallback((key) => translations[lang][key] ?? translations.ru[key] ?? key, [lang])
  const serverErrorKeys = {
    API_SERVER_UNAVAILABLE: 'apiUnavailable',
    'Email или пароль указаны неверно': 'invalidCredentials',
    'Аккаунт с таким email уже существует': 'emailAlreadyExists',
    'Укажите корректный email': 'invalidEmail',
    'Текущий пароль указан неверно': 'currentPasswordInvalid',
    'Имя должно содержать не менее 2 символов': 'nameTooShort',
    'Слишком много попыток. Попробуйте позже.': 'rateLimit',
    'Войдите в аккаунт': 'loginRequired',
    'Требуется вход администратора': 'adminLoginRequired',
    'Пароль должен содержать от 8 до 256 символов': 'passwordRange',
    'Внутренняя ошибка сервера': 'genericError',
    'Меню жүктөлгөн жок': 'menuLoadFailed',
    'Кошуу катасы': 'addFailed',
    'Жаңыртуу катасы': 'updateFailed',
    'Заказдар жүктөлгөн жок': 'ordersLoadFailed',
    'Заказ жиберүү катасы': 'orderFailed',
    'Укажите корректную дату бронирования': 'bookingDate',
    'Укажите корректное время': 'bookingTime',
    'Проверьте количество гостей': 'bookingGuests',
    'Укажите контактный телефон': 'bookingContact',
    'Добавьте товары в заказ': 'orderFailed',
    'Проверьте состав заказа': 'orderFailed',
    'Укажите имя': 'yourName',
    'Проверьте оценку': 'genericError',
    'Отзыв слишком короткий': 'genericError',
    'Не удалось выполнить запрос': 'genericError',
  }
  const translateError = useCallback((error) => {
    const key = serverErrorKeys[error?.message]
    return key ? t(key) : error?.message || t('genericError')
  }, [t])

  const changeLang = useCallback((nextLang) => {
    if (!Object.hasOwn(translations, nextLang)) return
    setLang(nextLang)
    localStorage.setItem('lang', nextLang)
  }, [])

  return (
    <LangContext.Provider value={{ lang, changeLang, t, translations, translateError }}>
      {children}
    </LangContext.Provider>
  )
}

export function useLang() {
  const context = useContext(LangContext)
  if (!context) throw new Error('useLang must be used within a LangProvider')
  return context
}
